// Normalise tuples into objects once.
export const menu = sections.map((s) => ({
  ...s,
  items: s.items.map(([no, name, price, variants, image, note]) => ({
    key: `${s.id}-${no}-${name}`,
    no,
    name,
    price,
    variants: variants || null,
    image: image || null,
    note: note || null,
  })),
}))

export const itemCount = menu.reduce((n, s) => n + s.items.length, 0)

// Split "14/16/18/ASP" into [{label, value}] for display and ordering.
export function priceOptions(item) {
  const parts = item.price.split('/').map((p) => p.trim())
  return parts.map((p, i) => {
    const num = p.toUpperCase() === 'ASP' ? null : Number(p)
    return {
      label: item.variants?.[i] || (parts.length > 1 ? `Option ${i + 1}` : null),
      value: num,
      raw: p,
    }
  })
}

export function formatPrice(value) {
  if (value == null) return 'ASP'
  return Number.isInteger(value) ? String(value) : value.toFixed(2)
}
